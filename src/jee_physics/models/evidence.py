class ExampleEvidenceRecord(BaseModel):
    """Source-grounded worked example."""
    example_id: str = Field(..., description="Deterministic example ID")
    source_id: str = Field(..., description="Originating source ID")
    page_range: List[int] = Field(..., description="[start_page, end_page]")
    title_or_label: str = Field("", description="Example number or title (e.g. Example 10.3)")
    title: Optional[str] = Field(None, description="Alternative alias for title_or_label")
    problem_statement: str = Field(..., description="Problem statement verbatim from source")
    source_method: str = Field(..., description="Method/solution steps from source")
    source_result: str = Field(..., description="Final result stated in source")
    relevant_figures: List[str] = Field(default_factory=list)
    taxonomy_node_ids: List[str] = Field(default_factory=list)
    truth_classification: EvidenceTruthClassification = Field(default=EvidenceTruthClassification.SOURCE_EXACT)
    fidelity_class: SourceFidelityClass = Field(default=SourceFidelityClass.SOURCE_DERIVED)
    fidelity_match: Optional[FidelityMatchResult] = Field(None)
    source_page_hash: Optional[str] = Field(None)

    @model_validator(mode="before")
    @classmethod
    def populate_title(cls, data: Any) -> Any:
        if isinstance(data, dict):
            if not data.get("title_or_label") and data.get("title"):
                data["title_or_label"] = data["title"]
            elif not data.get("title") and data.get("title_or_label"):
                data["title"] = data["title_or_label"]
        return data


