from datetime import datetime, timezone
from enum import Enum
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field, model_validator


class EvidenceType(str, Enum):
    """Semantic category of a granular physics evidence unit."""
    DEFINITION = "DEFINITION"
    CONCEPT_EXPLANATION = "CONCEPT_EXPLANATION"
    EXPOSITION = "EXPOSITION"
    DERIVATION = "DERIVATION"
    WORKED_EXAMPLE = "WORKED_EXAMPLE"
    THEOREM_PRINCIPLE = "THEOREM_PRINCIPLE"
    LAW = "LAW"
    FORMULA_EXPLANATION = "FORMULA_EXPLANATION"
    FIGURE_EXPLANATION = "FIGURE_EXPLANATION"
    PROBLEM = "PROBLEM"
    SOLUTION = "SOLUTION"
    MOCK_QUESTION = "MOCK_QUESTION"


class SourceFidelityClass(str, Enum):
    """Explicit source fidelity classification for Phase 11.9.1."""
    SOURCE_VERBATIM = "SOURCE_VERBATIM"      # Verbatim text directly present in source (whitespace/hyphen normalized)
    SOURCE_VISUAL = "SOURCE_VISUAL"          # Scanned/image source verified visually (Feynman)
    SOURCE_DERIVED = "SOURCE_DERIVED"        # Mathematically structured/normalized from source (formulas, tables, steps)
    PROJECT_DERIVED = "PROJECT_DERIVED"      # Project created (taxonomy, statistics, relations)
    INDEX_METADATA = "INDEX_METADATA"        # Generated structural metadata about source


class FidelityMatchResult(str, Enum):
    """Outcome of independent source page verification (Phase 11.9.1)."""
    EXACT_MATCH = "EXACT_MATCH"
    NORMALIZED_MATCH = "NORMALIZED_MATCH"
    PARTIAL_MATCH = "PARTIAL_MATCH"
    NO_MATCH = "NO_MATCH"
    VISUAL_ONLY = "VISUAL_ONLY"
    EXTRACTION_UNCERTAIN = "EXTRACTION_UNCERTAIN"


class EvidenceTruthClassification(str, Enum):
    """Hard boundary classification between authentic source content and project metadata (Phase 11.9)."""
    SOURCE_EXACT = "SOURCE_EXACT"          # Content directly extracted verbatim from PDF
    SOURCE_VERBATIM = "SOURCE_VERBATIM"    # Verbatim text directly present in source
    SOURCE_VISUAL = "SOURCE_VISUAL"        # Scanned/image source verified visually
    SOURCE_DERIVED = "SOURCE_DERIVED"      # Mathematically structured/normalized from source
    INDEX_METADATA = "INDEX_METADATA"      # Generated structural metadata describing source
    PROJECT_DERIVED = "PROJECT_DERIVED"    # Generated by project from evidence (taxonomy, relations)
    VERIFICATION_DERIVED = "VERIFICATION_DERIVED"  # Created during verification/adjudication


class TaxonomyMappingQuality(str, Enum):
    """Classification of precision for project-derived taxonomy mappings (Phase 11.9)."""
    DIRECT = "DIRECT"                      # Exact one-to-one mapping to target JEE node
    RELATED = "RELATED"                    # Closely related concept within same chapter/domain
    BROAD_CHAPTER_ONLY = "BROAD_CHAPTER_ONLY" # General topic mapping at chapter root level
    UNCERTAIN = "UNCERTAIN"                # Tentative or ambiguous mapping


class ExtractionQuality(str, Enum):
    """Assessment of text extraction reliability for a page or fragment."""
    EXCELLENT = "EXCELLENT"            # Clean digital text streams with math symbols intact
    GOOD = "GOOD"                      # Readable text with minor spacing or OCR quirks
    DEGRADED = "DEGRADED"              # Poor text stream requiring heuristic recovery
    NORMALIZED_FONT = "NORMALIZED_FONT"# Text recovered via font-table offset decode (e.g. HCV2)
    VECTORIZED_GLYPHS = "VECTORIZED_GLYPHS"  # Outlined vector glyphs without digital text font stream
    EMPTY = "EMPTY"                    # Blank page, cover, or purely unextractable
    VISUALLY_EXTRACTED_FROM_SOURCE = "VISUALLY_EXTRACTED_FROM_SOURCE"  # Scanned or image-only page verified visually



class PageEvidenceRecord(BaseModel):
    """Deterministic page-level audit record for each page across all corpus PDFs."""
    source_id: str = Field(..., description="Unique source identifier")
    pdf_page_number: int = Field(..., ge=1, description="1-based PDF file page index")
    printed_page_number: Optional[str] = Field(None, description="Printed header/footer page number if identifiable")
    extraction_quality: ExtractionQuality = Field(..., description="Classification of text extraction")
    text_length: int = Field(..., ge=0, description="Extracted character count")
    is_corrupted: bool = Field(False, description="Whether text stream appears corrupted or garbled")
    has_equations: bool = Field(False, description="Whether page contains mathematical expressions")
    has_figures: bool = Field(False, description="Whether page contains illustrations or diagrams")
    has_tables: bool = Field(False, description="Whether page contains data or classification tables")
    has_examples: bool = Field(False, description="Whether page contains worked/illustrative examples")
    has_exercises_problems: bool = Field(False, description="Whether page contains end-of-chapter or practice questions")
    section_or_chapter_heading: Optional[str] = Field(None, description="Identified chapter or section header")
    text_snippet: Optional[str] = Field(None, description="Representative ~150-char diagnostic text preview")


class SourceEvidenceRecord(BaseModel):
    """Granular semantic evidence unit extracted verbatim from a source page range."""
    evidence_id: str = Field(..., description="Deterministic unique evidence ID")
    source_id: str = Field(..., description="Parent source document ID")
    source_segment_id: Optional[str] = Field(None, description="Parent coarse segment ID")
    page_start: int = Field(..., ge=1, description="Starting 1-based PDF page")
    page_end: int = Field(..., ge=1, description="Ending 1-based PDF page")
    section_or_chapter: str = Field(..., description="Section title or chapter heading")
    section: Optional[str] = Field(None, description="Alias for section_or_chapter")
    evidence_type: EvidenceType = Field(..., description="Type of physics evidence")
    content_text: str = Field(..., description="Exact raw/extracted source text (unmodified)")
    extraction_quality: ExtractionQuality = Field(ExtractionQuality.GOOD)
    extraction_method: Optional[str] = Field("DIGITAL_TEXT", description="Method used: DIGITAL_TEXT, FONT_DECODED, VISUALLY_VERIFIED, OCR_RECOVERED")
    taxonomy_node_ids: List[str] = Field(default_factory=list, description="Authoritative taxonomy node IDs")
    figure_refs: List[str] = Field(default_factory=list, description="Associated figure evidence IDs")
    equation_refs: List[str] = Field(default_factory=list, description="Associated formula evidence IDs")
    problem_number: Optional[str] = Field(None, description="Problem label/number if applicable")
    parent_evidence_id: Optional[str] = Field(None, description="Parent evidence unit ID if nested")
    child_evidence_ids: List[str] = Field(default_factory=list, description="Child evidence unit IDs")
    provenance: Dict[str, Any] = Field(default_factory=dict, description="Bibliographic citation & page bounds")
    truth_classification: EvidenceTruthClassification = Field(
        default=EvidenceTruthClassification.SOURCE_EXACT,
        description="Hard distinction: SOURCE_EXACT vs INDEX_METADATA vs PROJECT_DERIVED vs VERIFICATION_DERIVED",
    )
    mapping_quality: TaxonomyMappingQuality = Field(
        default=TaxonomyMappingQuality.DIRECT,
        description="Quality of taxonomy mapping: DIRECT, RELATED, BROAD_CHAPTER_ONLY, UNCERTAIN",
    )
    fidelity_class: SourceFidelityClass = Field(
        default=SourceFidelityClass.SOURCE_VERBATIM,
        description="Phase 11.9.1 Fidelity class: SOURCE_VERBATIM, SOURCE_VISUAL, SOURCE_DERIVED, PROJECT_DERIVED, INDEX_METADATA",
    )
    fidelity_match: Optional[FidelityMatchResult] = Field(None, description="Independent verification match result")
    source_page_hash: Optional[str] = Field(None, description="SHA-256 fingerprint of normalized source page text")
    evidence_content_hash: Optional[str] = Field(None, description="SHA-256 fingerprint of normalized evidence text")

    @model_validator(mode="before")
    def set_section_alias(cls, values: Any) -> Any:
        if isinstance(values, dict):
            if "section" in values and "section_or_chapter" not in values:
                values["section_or_chapter"] = values["section"]
            elif "section_or_chapter" in values and "section" not in values:
                values["section"] = values["section_or_chapter"]

            # Content text normalization
            if "content_text" not in values:
                if "clean_text" in values and values["clean_text"]:
                    values["content_text"] = values["clean_text"]
                elif "raw_text" in values and values["raw_text"]:
                    values["content_text"] = values["raw_text"]

            # Quality normalization
            q = values.get("extraction_quality")
            if q in ("HIGH", "EXCELLENT"):
                values["extraction_quality"] = ExtractionQuality.EXCELLENT
            elif q in ("MEDIUM", "GOOD"):
                values["extraction_quality"] = ExtractionQuality.GOOD
            elif q == "LOW":
                values["extraction_quality"] = ExtractionQuality.DEGRADED
        return values

    @model_validator(mode="after")
    def validate_pages(self) -> "SourceEvidenceRecord":
        if self.page_start > self.page_end:
            raise ValueError(f"page_start ({self.page_start}) cannot exceed page_end ({self.page_end})")
        return self


